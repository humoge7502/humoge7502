def mission_card(c, idx, title, subtitle, status, version, threat, proof, pips, accent=None):
    """GTA-mission-dossier-style header card. Evidence table lives in markdown below."""
    acc = accent or c["green"]
    W, H = MISSION_W, MISSION_H
    parts = []
    parts.append(chassis(c, W, H, rx=8))
    # cinematic letterbox bars
    parts.append(f'<rect x="0" y="0" width="{W}" height="10" fill="{c["black"]}"/>')
    parts.append(f'<rect x="0" y="0" width="{W}" height="3" fill="{acc}" opacity="0.8"/>')
    parts.append(f'<rect x="0" y="{H-10}" width="{W}" height="10" fill="{c["black"]}"/>')
    parts.append(f'<rect x="0" y="{H-3}" width="{W}" height="3" fill="{acc}" opacity="0.35"/>')

    # mission index + title
    parts.append(mono(f'x="36" y="52" font-size="14" font-weight="700" letter-spacing="4"', c["muted"], f"MISSION {idx:02d}"))
    parts.append(f'<g font-family="{MONO}" font-size="34" font-weight="800" letter-spacing="1.5"><text x="36" y="92" fill="{c["text"]}">{esc(title)}</text></g>')
    parts.append(mono(f'x="38" y="118" font-size="13" letter-spacing="0.4"', c["muted"], esc(subtitle)))

    # status block, right side
    sx = W - 316
    parts.append(f'<rect x="{sx}" y="30" width="280" height="88" rx="6" fill="{c["panel2"]}" stroke="{c["line"]}"/>')
    parts.append(blink_dot(c, sx + 24, 52, r=4, color=acc, dur="2.2s"))
    parts.append(mono(f'x="{sx+40}" y="56" font-size="12" font-weight="700" letter-spacing="2"', acc, f"STATUS · {esc(status)}"))
    parts.append(mono(f'x="{sx+20}" y="80" font-size="11.5" letter-spacing="1.5"', c["muted"], f"PATCH {esc(version)}"))
    # difficulty pips
    px = sx + 20
    for i in range(5):
        filled = i < pips
        col = acc if filled else c["line2"]
        parts.append(f'<rect x="{px + i*24}" y="92" width="17" height="7" rx="1" fill="{col}" opacity="{1 if filled else 0.55}"/>')
    parts.append(mono(f'x="{px+5*24+10}" y="99" font-size="9.5" letter-spacing="1.2"', c["faint"], "DIFFICULTY"))

    # bottom telemetry line
    parts.append(mono(f'x="36" y="{H-20}" font-size="11.5" letter-spacing="0.5"', c["faint"],
                      f"THREAT: {esc(threat)}   ·   PROOF: {esc(proof)}"))
    # depth: soft top glow under the letterbox bar
    parts.append(f'<rect x="0" y="10" width="{W}" height="26" fill="{acc}" opacity="0.05"/>')
    parts.append(scanlines(c, W, H, opacity="0.06"))
    body = "\n".join(p for p in parts if p.strip())
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="Mission {idx:02d}: {esc(title)} — {esc(subtitle)}. Status {esc(status)}, patch {esc(version)}.">
<!-- {GENERATED_BY} -->
{body}
</svg>
"""
    return svg


