def esc(s):
    """XML-escape text for SVG."""
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace('"', "&quot;"))


def _fmt(n):
    """Strip trailing zeros from floats for clean path data."""
    return f"{n:.2f}".rstrip("0").rstrip(".")


