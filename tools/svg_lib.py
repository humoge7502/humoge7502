def section_strip(c, num, title, tag):
    """Full-width console strip: letterbox rules, section index, tag, caret.
    Rendered under a real markdown heading so text stays selectable."""
    W, H = STRIP_W, STRIP_H
    y_mid = H / 2 + 4
    bar_y = 8
    parts = []
    parts.append(chassis(c, W, H, rx=6))
    # GTA-style letterbox rules top and bottom
    parts.append(f'<rect x="0" y="{bar_y}" width="{W}" height="2" fill="{c["green"]}" opacity="0.75"/>')
    parts.append(f'<rect x="0" y="{H-bar_y-2}" width="{W}" height="2" fill="{c["line2"]}"/>')
    # left index block
    parts.append(f'<rect x="18" y="{_fmt(H/2-13)}" width="52" height="26" rx="4" fill="{c["panel2"]}" stroke="{c["line"]}"/>')
    parts.append(mono(f'x="44" y="{_fmt(y_mid)}" font-size="13" font-weight="700" text-anchor="middle" letter-spacing="1"',
                      c["green"], f"//{num}"))
    # title echo (decorative; real text lives in the markdown heading)
    parts.append(mono(f'x="88" y="{_fmt(y_mid)}" font-size="13" font-weight="700" letter-spacing="3.5"',
                      c["text"], esc(title.upper())))
    # tag chip right
    tw = 8 * len(tag) + 34
    parts.append(f'<rect x="{W-tw-52}" y="{_fmt(H/2-11)}" width="{tw}" height="22" rx="11" fill="{c["panel2"]}" stroke="{c["line"]}"/>')
    parts.append(mono(f'x="{W-52-tw/2}" y="{_fmt(y_mid)}" font-size="11" letter-spacing="1" text-anchor="middle"',
                      c["muted"], esc(tag)))
    parts.append(caret(c, W - 34, y_mid + 1, size=13, color=c["green"]))
    # tick ruler + circuit trace
    parts.append(dither_strip(c, 88, H - 16, min(320, W // 3), c["line2"], cell=3, rows=1, opacity="0.6"))
    parts.append(f'<path d="M {88 + min(340, W // 3)} {_fmt(H/2)} H {_fmt(W - tw - 70)}" stroke="{c["line"]}" stroke-width="1" stroke-dasharray="6 5" opacity="0.9"/>')
    parts.append(f'<circle cx="{_fmt(88 + min(340, W // 3))}" cy="{_fmt(H/2)}" r="2.2" fill="{c["green"]}"/>')
    # corner "screws" — pixel squares anchoring the chassis
    for sx_, sy_ in [(12, 12), (W - 16, 12), (12, H - 16), (W - 16, H - 16)]:
        parts.append(f'<rect x="{sx_}" y="{sy_}" width="4" height="4" fill="{c["line2"]}"/>')
    body = "\n".join(parts)
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="{esc(tag)}">
<!-- {GENERATED_BY} -->
{body}
</svg>
"""
    return svg


