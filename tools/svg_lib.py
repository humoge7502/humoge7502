def _hex_badge(c, cx, cy, r, color, title, sub, pulse=False):
    pts = " ".join(f"{_fmt(cx + r*_cos(60*i-30))},{_fmt(cy - r*_sin(60*i-30))}" for i in range(6))
    ring = f'<polygon points="{pts}" fill="{c["panel2"]}" stroke="{color}" stroke-width="2"/>'
    inner = f'<polygon points="{pts}" fill="none" stroke="{color}" stroke-width="1" opacity="0.35" transform="translate({_fmt(cx)} {_fmt(cy)}) scale(0.78) translate({_fmt(-cx)} {_fmt(-cy)})"/>'
    anim = ""
    if pulse:
        anim = (f'<polygon points="{pts}" fill="{color}" opacity="0">'
                f'<animate attributeName="opacity" values="0;0.18;0" dur="3s" repeatCount="indefinite"/>'
                f'</polygon>')
    txt = (mono(f'x="{_fmt(cx)}" y="{_fmt(cy + r + 26)}" font-size="11.5" font-weight="700" letter-spacing="0.6" text-anchor="middle"', c["text"], esc(title))
           + mono(f'x="{_fmt(cx)}" y="{_fmt(cy + r + 42)}" font-size="10" text-anchor="middle"', c["muted"], esc(sub)))
    return f"  {ring}\n  {inner}\n  {anim}\n  {txt}"


def _cos(deg):
    import math
    return math.cos(math.radians(deg))


def _sin(deg):
    import math
    return math.sin(math.radians(deg))


def achievements_strip(c, items, pulse_last=True):
    """Row of hexagonal achievement emblems. items: (title, sub, color, icon_svg)."""
    W, H = ACH_W, ACH_H
    n = len(items)
    parts = [chassis(c, W, H, rx=8)]
    parts.append(f'<rect x="0" y="0" width="{W}" height="3" fill="{c["amber"]}" opacity="0.55"/>')
    # caption left
    parts.append(mono(f'x="28" y="{_fmt(H/2-6)}" font-size="12" font-weight="700" letter-spacing="2"', c["amber"], "UNLOCKED"))
    parts.append(mono(f'x="28" y="{_fmt(H/2+14)}" font-size="10.5"', c["faint"], "receipt-checked"))
    parts.append(mono(f'x="28" y="{_fmt(H/2+29)}" font-size="10.5"', c["faint"], "no vanity unlocks"))
    # vertical divider
    parts.append(f'<rect x="150" y="24" width="1" height="{H-48}" fill="{c["line"]}"/>')
    # connecting circuit trace behind the badges
    parts.append(f'<path d="M 178 {_fmt(H/2-12)} H {_fmt(W-22)}" stroke="{c["line"]}" stroke-width="1" stroke-dasharray="3 6" opacity="0.8"/>')
    # badges
    span = W - 170 - 20
    step = span / n
    for i, (title, sub, color, icon) in enumerate(items):
        cx = 170 + step * (i + 0.5)
        cy = H / 2 - 12
        pulse = pulse_last and i == n - 1
        parts.append(_hex_badge(c, cx, cy, 26, color, title, sub, pulse=pulse))
        if icon:
            parts.append(icon(cx, cy, color))
    parts.append(scanlines(c, W, H, opacity="0.05"))
    body = "\n".join(parts)
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="Achievements unlocked: {esc('; '.join(i[0] for i in items))} — all verifiable from repository history.">
<!-- {GENERATED_BY} -->
{body}
</svg>
"""
    return svg


