def pixel_brackets(c, x, y, w, h, size=10, color=None, sw=2):
    """Four L-shaped corner brackets — the 'target lock' frame."""
    col = color or c["green"]
    g = size
    return f"""
  <path d="M {_fmt(x)} {_fmt(y+g)} V {_fmt(y)} H {_fmt(x+g)}" fill="none" stroke="{col}" stroke-width="{sw}"/>
  <path d="M {_fmt(x+w-g)} {_fmt(y)} H {_fmt(x+w)} V {_fmt(y+g)}" fill="none" stroke="{col}" stroke-width="{sw}"/>
  <path d="M {_fmt(x+w)} {_fmt(y+h-g)} V {_fmt(y+h)} H {_fmt(x+w-g)}" fill="none" stroke="{col}" stroke-width="{sw}"/>
  <path d="M {_fmt(x+g)} {_fmt(y+h)} H {_fmt(x)} V {_fmt(y+h-g)}" fill="none" stroke="{col}" stroke-width="{sw}"/>"""


def dither_strip(c, x, y, w, color, cell=4, rows=1, opacity="0.5"):
    """A row/rows of checkered 2px squares — restrained pixel accent."""
    rects = []
    for r in range(rows):
        for i in range(0, w, cell * 2):
            if i + cell <= w:
                rects.append(
                    f'<rect x="{_fmt(x+i)}" y="{_fmt(y+r*cell)}" width="{cell}" height="{cell}" fill="{color}"/>')
    body = "\n  ".join(rects)
    return f'\n  <g opacity="{opacity}">\n  {body}\n  </g>'


def blink_dot(c, x, y, r=4, color=None, dur="2.4s"):
    """Status LED with a soft SMIL pulse (GitHub-safe inside <img>)."""
    col = color or c["green"]
    return f"""
  <circle cx="{_fmt(x)}" cy="{_fmt(y)}" r="{r}" fill="{col}"/>
  <circle cx="{_fmt(x)}" cy="{_fmt(y)}" r="{r}" fill="{col}" opacity="0.25">
    <animate attributeName="r" values="{r};{r*2.4};{r}" dur="{dur}" repeatCount="indefinite"/>
    <animate attributeName="opacity" values="0.35;0;0.35" dur="{dur}" repeatCount="indefinite"/>
  </circle>"""


def caret(c, x, y, size=16, color=None, dur="1.1s"):
    """Blinking terminal cursor block."""
    col = color or c["green"]
    return f"""
  <rect x="{_fmt(x)}" y="{_fmt(y - size*0.8)}" width="{size*0.62:.0f}" height="{size}" fill="{col}">
    <animate attributeName="opacity" values="1;1;0;0;1" keyTimes="0;0.5;0.5;0.98;1" dur="{dur}" repeatCount="indefinite"/>
  </rect>"""


def glitch_title(c, x, y, text, size=30, weight=800, letter=2, fill=None,
                 ghost_dx=2.5, flicker="0s;1.8s;1.86s;1.92s;4s"):
    """Chromatic-aberration title: cyan + red ghosts flicker around white text.
    Ghosts are mostly invisible and flare briefly — GTA- cinematic, not noisy."""
    base = fill or c["text"]
    return f"""
  <g font-family="{MONO}" font-size="{size}" font-weight="{weight}" letter-spacing="{letter}">
    <text x="{_fmt(x+ghost_dx)}" y="{y}" fill="{c['cyan']}" opacity="0">{text}</text>
    <text x="{_fmt(x-ghost_dx)}" y="{_fmt(y+0.5)}" fill="{c['red']}" opacity="0">{text}</text>
    <text x="{x}" y="{y}" fill="{base}">{text}</text>
  </g>
  <g font-family="{MONO}" font-size="{size}" font-weight="{weight}" letter-spacing="{letter}">
    <text x="{_fmt(x+ghost_dx)}" y="{y}" fill="{c['cyan']}" opacity="0">
      {text}
      <animate attributeName="opacity" values="0;0;0.55;0;0" keyTimes="0;0.44;0.47;0.5;1" dur="5.2s" repeatCount="indefinite"/>
    </text>
    <text x="{_fmt(x-ghost_dx)}" y="{y}" fill="{c['red']}" opacity="0">
      {text}
      <animate attributeName="opacity" values="0;0;0.4;0;0" keyTimes="0;0.45;0.48;0.51;1" dur="5.2s" repeatCount="indefinite"/>
    </text>
  </g>"""


def scanlines(c, w, h, opacity="0.05", line=1.5, gap=3.5):
    """CRT scanline overlay pattern."""
    return f"""
  <defs>
    <pattern id="scan" width="4" height="{_fmt(line+gap)}" patternUnits="userSpaceOnUse">
      <rect width="4" height="{line}" fill="{c['black']}" opacity="0.9"/>
    </pattern>
  </defs>
  <rect width="{w}" height="{h}" fill="url(#scan)" opacity="{opacity}" pointer-events="none"/>"""


def chassis(c, w, h, rx=10, fill=None, stroke=None, sw=1):
    """The outer device body of a panel."""
    return (f'<rect x="0" y="0" width="{w}" height="{h}" rx="{rx}" '
            f'fill="{fill or c["bg"]}" stroke="{stroke or c["line"]}" stroke-width="{sw}"/>')


def mono(text_attrs="", fill="", content=""):
    return (f'<text font-family="{MONO}" {text_attrs} fill="{fill}">'
            f'{content}</text>')


